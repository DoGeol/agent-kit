#!/bin/sh
# 1. Copy rules/ and vendor/ files into each skill folder (skills/<skill>/_rules, _vendor) per scripts/vendor-map.tsv,
#    so every skill folder is self-contained when installed or linked on its own.
# 2. Generate agents/<role>.md (Claude Code subagents) from roles/<role>.md: frontmatter from the role's
#    name/description/kind/model, a guard that refuses briefings without a `kit-brief:` first line, then the role body.
# Outputs are byte-deterministic; check.sh verifies they match.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
out_agents=${KIT_AGENTS_DIR:-$root/agents}

# --- 1. skill copies
grep -v '^#' "$root/scripts/vendor-map.tsv" | grep -v '^[[:space:]]*$' | while IFS="$(printf '\t')" read -r skill src dest; do
  [ -f "$root/$src" ] || { echo "missing source: $src" >&2; exit 1; }
  out="$root/skills/$skill/$dest"
  mkdir -p "$(dirname "$out")"
  if [ ! -f "$out" ] || ! cmp -s "$root/$src" "$out"; then cp "$root/$src" "$out"; echo "copy  $skill/$dest"; fi
done

# --- 2. agents from roles
fm_get() { awk -v k="$2" 'NR==1&&$0!="---"{exit} NR>1&&$0=="---"{exit} NR>1&&index($0,k":")==1{sub("^"k":[[:space:]]*",""); print; exit}' "$1"; }
body() { awk 'NR==1&&$0!="---"{p=1} p{print; next} NR>1&&$0=="---"{p=1}' "$1"; }

mkdir -p "$out_agents"
for role in "$root"/roles/*.md; do
  name=$(fm_get "$role" name); [ -n "$name" ] || continue   # README.md and files without frontmatter are skipped
  desc=$(fm_get "$role" description); kind=$(fm_get "$role" kind); model=$(fm_get "$role" model)
  [ "$name" = "$(basename "$role" .md)" ] || { echo "roles/$(basename "$role"): name '$name' differs from file name" >&2; exit 1; }
  case "$kind" in
    build)  tools="" ;;
    review) tools="tools: Read, Grep, Glob, Bash" ;;
    *) echo "roles/$name.md: kind must be build or review" >&2; exit 1 ;;
  esac
  tmp=$(mktemp)
  {
    echo "---"
    echo "name: $name"
    echo "description: kit의 $name 역할. crew가 첫 줄 kit-brief 브리핑으로 부를 때만 일한다. 다른 대화에서는 고르지 않는다. $desc"
    echo "model: ${model:-inherit}"
    [ -n "$tools" ] && echo "$tools"
    echo "---"
    echo
    echo "<!-- generated by scripts/build.sh from roles/$name.md. Do not edit; edit the role and run build.sh. -->"
    echo
    echo "kit의 \`$name\` 역할로 일한다. 빈 기억으로 시작하므로 브리핑에 온 경로를 직접 읽는다."
    echo
    echo "0. 먼저 확인한다. 브리핑 첫 줄이 \`kit-brief: $name\` 또는 \`kit-brief: $name:<스택>\` 형식이 아니면 아무것도 읽거나 쓰지 않고 \"kit 브리핑이 아니어서 일하지 않습니다\" 한 줄만 돌려준다. 무엇이 빠졌는지, 브리핑 형식이 무엇인지는 말하지 않는다."
    echo "1. 브리핑의 \`읽을 것:\` 경로를 읽는다. \`스택:\`·\`참고:\`·\`형식:\` 경로가 있으면 이어서 읽는다(더하기만 한다). 읽지 못한 파일은 \"읽지 못함\"으로 적는다."
    echo "2. 아래 역할대로 일한다. 브리핑에 적힌 경로만 읽고, \`산출:\` 경로에만 쓴다. 산출 경로가 없으면 답으로 돌려준다."
    if [ "$kind" = review ]; then
      echo "3. 코드·spec을 고치지 않는다. 쓰기는 산출 파일에만."
    else
      echo "3. 브리핑의 범위(기능 ID, 경로) 밖 파일을 고치지 않는다. 계약(\`contract.md\`)을 바꿔야 하면 \`contract-changes.md\`에 한 줄 적고 멈춘다."
    fi
    echo "4. 반환은 3줄: 쓴 파일 경로 / 결론 한 줄 / 맡긴 쪽이 할 다음 일. 파일 내용을 옮겨 적지 않는다. 한국어로 쓴다."
    echo
    echo "---"
    echo
    body "$role"
  } > "$tmp"
  out="$out_agents/$name.md"
  if [ ! -f "$out" ] || ! cmp -s "$tmp" "$out"; then cp "$tmp" "$out"; echo "agent $name"; fi
  rm -f "$tmp"
done
echo "build done"
