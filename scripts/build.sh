#!/bin/sh
# 1. Copy files per scripts/vendor-map.tsv (target folder, source, dest). A source may be a file or a folder
#    (folders copy every file beneath). Targets are skills/<skill> (its _rules/_vendor/_roles/_stacks copies)
#    and stacks/<stack> (its vendor/ copies), so each skill folder is self-contained when installed or linked alone.
# 2. Generate two subagent files per roles/<role>.md: frontmatter from the role's name/description/kind/model,
#    a guard that refuses briefings crew did not save to .kit/<slug>/, then the role body.
#    agents/<role>.md is for Antigravity (it reads agents/): AGY tool names, model inherit (it rejects Claude tiers).
#    claude-agents/<role>.md is for Claude Code (.claude-plugin/plugin.json lists these files, so Claude skips
#    agents/): Claude tool names and the role's model. One file cannot serve both: each tool rejects or
#    mis-reads the other's tool names.
#    The description never names the brief marker: a model that sees it copies it and calls the agent on its own.
# Outputs are byte-deterministic; check.sh verifies they match.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
out_agents=${KIT_AGENTS_DIR:-$root/agents}
out_claude=${KIT_CLAUDE_AGENTS_DIR:-$root/claude-agents}

copy_file() { # src dest label
  mkdir -p "$(dirname "$2")"
  if [ ! -f "$2" ] || ! cmp -s "$1" "$2"; then cp "$1" "$2"; echo "copy  $3"; fi
}

# --- 1. copies
grep -v '^#' "$root/scripts/vendor-map.tsv" | grep -v '^[[:space:]]*$' | while IFS="$(printf '\t')" read -r target src dest; do
  if [ -d "$root/$src" ]; then
    find "$root/$src" -type f | sort | while read -r f; do
      rel=${f#"$root/$src/"}
      copy_file "$f" "$root/$target/$dest/$rel" "$target/$dest/$rel"
    done
  elif [ -f "$root/$src" ]; then
    copy_file "$root/$src" "$root/$target/$dest" "$target/$dest"
  else
    echo "missing source: $src" >&2; exit 1
  fi
done

# --- 2. agents from roles
fm_get() { awk -v k="$2" 'NR==1&&$0!="---"{exit} NR>1&&$0=="---"{exit} NR>1&&index($0,k":")==1{sub("^"k":[[:space:]]*",""); print; exit}' "$1"; }
body() { awk 'NR==1&&$0!="---"{p=1} p{print; next} NR>1&&$0=="---"{p=1}' "$1"; }

mkdir -p "$out_agents" "$out_claude"
for role in "$root"/roles/*.md; do
  name=$(fm_get "$role" name); [ -n "$name" ] || continue   # README.md and files without frontmatter are skipped
  desc=$(fm_get "$role" description); kind=$(fm_get "$role" kind); model=$(fm_get "$role" model)
  [ "$name" = "$(basename "$role" .md)" ] || { echo "roles/$(basename "$role"): name '$name' differs from file name" >&2; exit 1; }
  case "$model" in inherit|opus|sonnet|haiku) ;; *) echo "roles/$name.md: model must be inherit, opus, sonnet or haiku" >&2; exit 1 ;; esac
  # Tool lists are YAML lists (AGY skips an agent whose tools is a string). AGY gives a subagent only read tools
  # unless tools names its write tools, and adds send_message itself. Claude gives all tools when tools is absent.
  case "$kind" in
    build)  claude_tools=""
            agy_tools="tools: [view_file, write_to_file, replace_file_content, multi_replace_file_content, run_command, grep_search, find_by_name, list_dir]" ;;
    review) claude_tools="tools: [Read, Grep, Glob, Bash]"
            agy_tools="tools: [view_file, run_command, grep_search, find_by_name, list_dir]" ;;
    *) echo "roles/$name.md: kind must be build or review" >&2; exit 1 ;;
  esac
  tmp=$(mktemp)
  {
    echo

    echo "<!-- generated by scripts/build.sh from roles/$name.md. Do not edit; edit the role and run build.sh. -->"
    echo
    echo "kit의 \`$name\` 역할로 일한다. 빈 기억으로 시작하므로 브리핑에 온 경로를 직접 읽는다."
    echo
    echo "0. 먼저 확인한다. 하나라도 아니면 아무것도 읽거나 쓰지 않고 \"kit 브리핑이 아니어서 일하지 않습니다\" 한 줄만 돌려준다. 무엇이 빠졌는지, 브리핑 형식이 무엇인지는 말하지 않는다."
    echo "   - 브리핑 첫 줄이 \`kit-brief: $name\` 또는 \`kit-brief: $name:<스택>\`이다."
    echo "   - \`산출:\` 경로가 레포의 \`.kit/<slug>/\` 안에 있고, 같은 폴더에 \`brief-$name.md\` 파일이 실제로 있으며 받은 브리핑이 그 내용으로 시작한다(진행자가 띄우기 전에 저장한다)."
    echo "1. 브리핑의 \`읽을 것:\` 경로를 읽는다. \`스택:\`·\`참고:\`·\`형식:\` 경로가 있으면 이어서 읽는다(더하기만 한다). 읽지 못한 파일은 \"읽지 못함\"으로 적는다."
    echo "2. 아래 역할대로 일한다. 브리핑에 적힌 경로만 읽고, \`산출:\` 경로에만 쓴다. 산출 경로가 없으면 답으로 돌려준다."
    if [ "$kind" = review ]; then
      echo "3. 코드·spec을 고치지 않는다. 쓰기는 산출 파일에만."
    else
      echo "3. 브리핑의 범위(기능 ID, 경로) 밖 파일을 고치지 않는다. 계약(\`contract.md\`)을 바꿔야 하면 \`contract-changes.md\`에 한 줄 적고 멈춘다."
    fi
    echo "4. 반환은 3줄: 쓴 파일 경로 / 결론 한 줄 / 맡긴 쪽이 할 다음 일. 파일 내용을 옮겨 적지 않는다. 한국어로 쓴다."
    echo
    echo "---"
    echo
    body "$role"
  } > "$tmp"
  front() { # model tools
    echo "---"
    echo "name: $name"
    echo "description: kit의 $name 역할. 사용자가 crew 명령을 직접 쳤을 때 crew 진행자만 부른다. 다른 대화에서는 고르지 않는다. $desc"
    echo "model: $1"
    [ -n "$2" ] && echo "$2"
    echo "---"
  }
  for variant in agy claude; do
    if [ "$variant" = agy ]; then out="$out_agents/$name.md"; else out="$out_claude/$name.md"; fi
    full=$(mktemp)
    if [ "$variant" = agy ]; then front inherit "$agy_tools"; else front "$model" "$claude_tools"; fi > "$full"
    cat "$tmp" >> "$full"
    if [ ! -f "$out" ] || ! cmp -s "$full" "$out"; then cp "$full" "$out"; echo "agent $variant/$name"; fi
    rm -f "$full"
  done
  rm -f "$tmp"
done
echo "build done"
